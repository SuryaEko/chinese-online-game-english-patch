<#
  English patch installer for "Chinese-Style Online Game" (MMOSimulator).
  Usage:  powershell -ExecutionPolicy Bypass -File install.ps1 -GamePath "D:\...\MMOSimulator\MMOSimulator"
          add -SkipTextures to install only the text translation.
  Downloads BepInEx and XUnity.AutoTranslator from their official GitHub releases.
#>
param(
    [Parameter(Mandatory = $true)][string]$GamePath,
    [switch]$SkipTextures
)
$ErrorActionPreference = 'Stop'
$BepInEx = 'https://github.com/BepInEx/BepInEx/releases/download/v6.0.0-pre.2/BepInEx-Unity.IL2CPP-win-x64-6.0.0-pre.2.zip'
$XUnity  = 'https://github.com/bbepis/XUnity.AutoTranslator/releases/download/v5.6.3.1/XUnity.AutoTranslator-BepInEx-IL2CPP-5.6.3.1.zip'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

if (-not (Test-Path (Join-Path $GamePath 'MMOSimulator.exe'))) { throw "MMOSimulator.exe not found in $GamePath" }
if (Get-Process MMOSimulator -ErrorAction SilentlyContinue) { throw 'Close the game first.' }

$tmp = Join-Path $env:TEMP 'mmo-english-patch'
New-Item -ItemType Directory -Force $tmp | Out-Null
foreach ($u in @($BepInEx, $XUnity)) {
    $zip = Join-Path $tmp ([IO.Path]::GetFileName($u))
    Write-Host "Downloading $u"
    Invoke-WebRequest -Uri $u -OutFile $zip -UseBasicParsing
    Expand-Archive -Path $zip -DestinationPath $GamePath -Force
}

$text = Join-Path $GamePath 'BepInEx\Translation\en\Text'
New-Item -ItemType Directory -Force $text, (Join-Path $GamePath 'BepInEx\config') | Out-Null
Copy-Item (Join-Path $here 'translation\_AutoGeneratedTranslations.txt') $text -Force
Copy-Item (Join-Path $here 'translation\_AutoGeneratedresizer.txt') $text -Force
Copy-Item (Join-Path $here 'translation\AutoTranslatorConfig.ini') (Join-Path $GamePath 'BepInEx\config') -Force
Write-Host 'Text translation installed.'

if (-not $SkipTextures) {
    python (Join-Path $here 'textures\patch_textures.py') $GamePath
    if ($LASTEXITCODE -ne 0) { Write-Warning 'Texture patch failed or was skipped (needs Python 3 + Pillow). Text translation still works.' }
}
Write-Host 'Done. Start the game; the first launch takes a minute while BepInEx builds its files.'
