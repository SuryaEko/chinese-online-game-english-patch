"""Add observed-text translations, derive plain segment entries from tagged keys, rebuild the cache."""
import glob, json, os, re

S = os.path.dirname(os.path.abspath(__file__))
han = re.compile("[\u3400-\u9fff]")
final = json.load(open(S + "/final.json", encoding="utf-8"))
obs = json.load(open(S + "/obs_miss.json", encoding="utf-8"))
for f in sorted(glob.glob(S + "/tr4/o*.txt")):
    for ln in open(f, encoding="utf-8"):
        ln = ln.rstrip("\n")
        if ln:
            i, _, t = ln.partition("|")
            final[obs[int(i)].strip()] = t.replace("<NL>", "\n").strip()

# plain segment entries (so the colour-wrapper regex can translate each segment separately)
tag = re.compile(r"<[^>]*>")
added = 0
for k, v in list(final.items()):
    if len(k) > 120 or "<" not in k:
        continue
    kp, vp = tag.split(k), tag.split(v)
    if len(kp) != len(vp):
        continue
    for a, b in zip(kp, vp):
        a, b = a.strip(), b.strip()
        if a and b and han.search(a) and a not in final and not han.search(b):
            final[a] = b
            added += 1
print("segment entries added", added)
# fixed chat labels
final.update({"[系统]": "[System]", "[世界]": "[World]", "[帮会]": "[Guild]", "[当前]": "[Current]", "[开]": "[Open]"})
json.dump(final, open(S + "/final.json", "w", encoding="utf-8"), ensure_ascii=False)


def esc(s):
    return s.replace("\\", "\\\\").replace("=", "\\=").replace("\r", "\\r").replace("\n", "\\n")


lines = [esc(z.strip()) + "=" + esc(e.strip()) for z, e in final.items() if z.strip()]
lines += open(S + "/regex.txt", encoding="utf-8").read().splitlines()
open(S + "/_AutoGeneratedTranslations.new.txt", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("lines", len(lines))
