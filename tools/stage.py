"""Stage the GitHub repo: textures (png + manifest), translation files, tools."""
import json, os, pickle, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from glyphs import *  # noqa  (img_of, pids_of, IDX)
from PIL import Image

GAME = r"D:\SteamLibrary\steamapps\common\MMOSimulator\MMOSimulator"
REPO = os.path.join(HERE, "repo")
for sub in ("textures", "translation", "tools"):
    os.makedirs(os.path.join(REPO, sub), exist_ok=True)

# 1) edited images, keyed by pathID (later plans override earlier ones, same as applied order)
final = {}
for n in ("plan1.pkl", "plan2.pkl", "plan3.pkl"):
    for ci, img in pickle.load(open(os.path.join(HERE, n), "rb")):
        for pid in pids_of(ci):
            final[pid] = img
# logo (pathID 1831) was patched by run_logo.py
sys.argv = ["x"]
from imgtool import grad_text_layer, load
o = load("Logo - 副本")
final[1831] = grad_text_layer(o.size, ["CHINESE-STYLE ONLINE GAME"], font_key="impact", box=(89, 120, 941, 259))

backed = json.load(open(os.path.join(GAME, "_texture_backup", "index.json"), encoding="utf-8"))
manifest = []
for pid in sorted(final):
    assert str(pid) in backed, pid
    i = IDX[pid]
    final[pid].save(os.path.join(REPO, "textures", f"{pid}.png"))
    manifest.append({"pid": pid, "name": i["name"], "fmt": i["fmt"], "mips": i["mip"], "w": i["w"], "h": i["h"],
                     "file": i["path"], "offset": i["off"], "size": i["ssize"]})
missing = set(map(int, backed)) - set(final)
print("images", len(final), "backup entries", len(backed), "not in plans:", sorted(missing))
sizes = {f: os.path.getsize(os.path.join(GAME, "MMOSimulator_Data", f)) for f in {m["file"] for m in manifest}}
json.dump({"game_build": "V1.43", "file_sizes": sizes, "textures": manifest},
          open(os.path.join(REPO, "textures", "manifest.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

# 2) translation files
t = os.path.join(GAME, "BepInEx", "Translation", "en", "Text")
shutil.copy(os.path.join(t, "_AutoGeneratedTranslations.txt"), os.path.join(REPO, "translation"))
shutil.copy(os.path.join(t, "_AutoGeneratedresizer.txt"), os.path.join(REPO, "translation"))
shutil.copy(os.path.join(GAME, "BepInEx", "config", "AutoTranslatorConfig.ini"), os.path.join(REPO, "translation"))

# 3) dev tools
for f in ("imgtool.py", "glyphs.py", "signs.py", "batch1.py", "batch2.py", "batch2b.py", "batch3.py", "batch4.py",
          "run_logo.py", "patcher.py", "extract.py", "build.py", "emit.py", "apply.py"):
    shutil.copy(os.path.join(HERE, f), os.path.join(REPO, "tools", f))
print("staged")
